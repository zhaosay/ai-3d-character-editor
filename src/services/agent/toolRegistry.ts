function rebuildBoundTargetPositionTrack(
  animation: AnimationData,
  propId: string,
  segments: PlanSegment[],
  props: StageProp[],
  scene: THREE.Group,
  snapshot: NonNullable<ReturnType<typeof useSkeletonStore.getState>['snapshot']>,
  targetDistance?: number,
): { tracks: BoneTrack[]; warnings: string[] } | null {
  const movementTemplates = new Set(['march', 'orient', 'sit', 'lie', 'sleep', 'reach', 'stand']);
  const ranges = segments.filter((segment) => segment.targetPropId === propId && movementTemplates.has(segment.template));
  if (ranges.length === 0) return null;

  const segmentInteractions = resolveSequentialInteractionFrames(segments, scene, snapshot, props,
    targetDistance === undefined ? undefined : { [propId]: targetDistance });
  const generated = generatePlannedTracks(buildBoneMap(snapshot), segments, animation.duration, 7,
    buildRestMap(snapshot), buildRestPositionMap(snapshot), null, {}, segmentInteractions,
    props.find((prop) => prop.kind === 'room')?.position[1] ?? 0,
    estimateGroundHipLocalOffset(scene, snapshot, props.find((prop) => prop.kind === 'room')?.position[1] ?? 0));
  const hipsName = buildBoneMap(snapshot).hips;
  if (!hipsName) return { tracks: animation.tracks, warnings: ['骨架未映射 hips，无法根据新道具位置重算走位轨道'] };
  const oldTrack = animation.tracks.find((track) => track.boneName === hipsName);
  const generatedTrack = generated.tracks.find((track) => track.boneName === hipsName);
  if (!generatedTrack?.position.length) return { tracks: animation.tracks, warnings: ['动作 Provider 未生成髋部位置轨道，场景目标已更新但走位未重算'] };
  const inAffectedRange = (time: number) => ranges.some((range) => time >= range.t0 - 1e-4 && time <= range.t1 + 1e-4);
  const byTime = new Map<number, BoneTrack['position'][number]>();
  for (const key of oldTrack?.position ?? []) if (!inAffectedRange(key.time)) byTime.set(key.time, key);
  for (const key of generatedTrack.position) if (inAffectedRange(key.time)) byTime.set(key.time, key);
  if (![...byTime.keys()].some((time) => ranges.some((range) => time >= range.t0 - 1e-4 && time <= range.t1 + 1e-4))) {
    return { tracks: animation.tracks, warnings: ['新场景目标没有可用的走位关键帧，原动画保持不变'] };
  }
  const position = [...byTime.values()].sort((a, b) => a.time - b.time);
  const nextTrack: BoneTrack = oldTrack
    ? { ...oldTrack, position }
    : { boneName: hipsName, position, rotation: [], scale: [] };
  return {
    tracks: oldTrack
      ? animation.tracks.map((track) => track === oldTrack ? nextTrack : track)
      : [...animation.tracks, nextTrack],
    warnings: generated.warnings,
  };
}

