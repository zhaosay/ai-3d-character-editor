function clauseOverlap(left: string, right: string): number {
  const bigrams = (value: string) => {
    const text = Array.from(value.toLowerCase().replace(/\s+/g, ''));
    return new Set(text.slice(0, -1).map((char, index) => `${char}${text[index + 1]}`));
  };
  const a = bigrams(left);
  const b = bigrams(right);
  if (a.size === 0 || b.size === 0) return 0;
  let shared = 0;
  for (const token of a) if (b.has(token)) shared += 1;
  return shared / (a.size + b.size - shared);
}

/** Carry rule-derived prop targets across LLM-inserted phases without relying on array indexes. */
function alignRuleSegments(
  modelSegments: PlanSegment[],
  ruleSegments: PlanSegment[],
  ambiguousPropIds: Set<string>,
  duration: number,
  completeMissing = false,
): { segments: PlanSegment[]; ruleToModel: Map<number, number>; restoredRuleSegments: PlanSegment[] } {
  const result = modelSegments.map((segment) => ({ ...segment }));
  const ruleToModel = new Map<number, number>();
  for (const segment of result) if (segment.targetPropId && ambiguousPropIds.has(segment.targetPropId)) delete segment.targetPropId;
  const rows = ruleSegments.length + 1;
  const columns = modelSegments.length + 1;
  const score = Array.from({ length: rows }, () => Array<number>(columns).fill(0));
  const matchScore = (rule: PlanSegment, model: PlanSegment) => rule.template === model.template
    ? 1000 + Math.round(clauseOverlap(rule.clause, model.clause) * 20)
    : Number.NEGATIVE_INFINITY;
  for (let i = ruleSegments.length - 1; i >= 0; i--) {
    for (let j = modelSegments.length - 1; j >= 0; j--) {
      score[i][j] = Math.max(
        score[i + 1][j],
        score[i][j + 1],
        matchScore(ruleSegments[i], modelSegments[j]) + score[i + 1][j + 1],
      );
    }
  }

  let i = 0;
  let j = 0;
  while (i < ruleSegments.length && j < modelSegments.length) {
    const matched = matchScore(ruleSegments[i], modelSegments[j]) + score[i + 1][j + 1];
    if (Number.isFinite(matched) && score[i][j] === matched) {
      ruleToModel.set(i, j);
      const targetPropId = ruleSegments[i].targetPropId;
      if (targetPropId && !ambiguousPropIds.has(targetPropId) && !result[j].targetPropId) result[j].targetPropId = targetPropId;
      i += 1;
      j += 1;
    } else if (score[i + 1][j] > score[i][j + 1]) i += 1;
    else j += 1;
  }
  const restoredRuleSegments: PlanSegment[] = [];
  if (completeMissing && ruleToModel.size > 0 && ruleToModel.size < ruleSegments.length) {
    const insertBefore = Array.from({ length: result.length + 1 }, () => [] as PlanSegment[]);
    for (let ruleIndex = 0; ruleIndex < ruleSegments.length; ruleIndex++) {
      if (ruleToModel.has(ruleIndex)) continue;
      let nextModelIndex: number | undefined;
      for (let next = ruleIndex + 1; next < ruleSegments.length; next++) {
        nextModelIndex = ruleToModel.get(next);
        if (nextModelIndex !== undefined) break;
      }
      if (nextModelIndex === undefined) {
        for (let previous = ruleIndex - 1; previous >= 0; previous--) {
          const previousModelIndex = ruleToModel.get(previous);
          if (previousModelIndex !== undefined) {
            nextModelIndex = previousModelIndex + 1;
            break;
          }
        }
      }
      const fallback = { ...ruleSegments[ruleIndex] };
      if (fallback.targetPropId && ambiguousPropIds.has(fallback.targetPropId)) delete fallback.targetPropId;
      insertBefore[nextModelIndex ?? result.length].push(fallback);
      restoredRuleSegments.push(fallback);
    }

    const ordered: PlanSegment[] = [];
    for (let index = 0; index <= result.length; index++) {
      ordered.push(...insertBefore[index]);
      if (index < result.length) ordered.push(result[index]);
    }
    const weights = ordered.map((segment) => Math.max(0.1, segment.t1 - segment.t0));
    const totalWeight = weights.reduce((total, weight) => total + weight, 0);
    let time = 0;
    const completed = ordered.map((segment, index) => {
      const t0 = time;
      time = index === ordered.length - 1 ? duration : time + duration * weights[index] / totalWeight;
      return { ...segment, t0, t1: time };
    });
    const remapped = alignRuleSegments(completed, ruleSegments, ambiguousPropIds, duration);
    return { ...remapped, restoredRuleSegments };
  }
  return { segments: result, ruleToModel, restoredRuleSegments };
}

